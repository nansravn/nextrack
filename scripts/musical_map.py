"""The musical map of a track: the file format, its schema checks and its (de)serialisation.

A pure library: no I/O besides `load_map`, and no heavy imports at module level (the
validator, `check_repo.py`, imports this). Schema: the "Musical maps" section of `lightshows/README.md`.
"""
from __future__ import annotations

import re
import unicodedata
from pathlib import Path

import yaml

MAP_VERSION = 1
VOICES = ("vocals", "kick", "perc", "bass", "other")
STEPS_PER_BAR = 16
SECTION_KINDS = ("intro", "groove", "break", "build", "drop", "outro")
REGISTERS = ("low", "mid", "high")
CUE_NAMES = "ABCDEFGH"

HEADER = "# Generated by scripts/nextrack_map.py analyze. Do not edit by hand."
KEYS = (
    "map_version", "track", "soundswitch", "audio", "grid", "grid_warning", "separator", "bars",
    "hot_cues", "hot_cues_note", "voices", "steps", "onsets", "register", "phrases", "sections",
    "drops", "silences",
)
REQUIRED = tuple(k for k in KEYS if k not in ("grid_warning", "hot_cues_note"))
BALANCE_VOICES = ("perc", "other")
ONSET_VOICES = ("kick", "perc")
STEP_CHUNK = 8 * STEPS_PER_BAR  # step strings hold 8 bars

GUID_RE = re.compile(r"[0-9A-Fa-f]{8}-[0-9A-Fa-f]{4}-[0-9A-Fa-f]{4}-[0-9A-Fa-f]{4}-[0-9A-Fa-f]{12}")
DOWNBEAT_RE = re.compile(r"([0-9]+):([0-5][0-9])\.([0-9]{3})")
SHA_RE = re.compile(r"[0-9a-f]{12}")
CUE_RE = re.compile(r"[1-9][0-9]*\.[1-4]([+-][0-9]+ms)?")
BEAT_RE = re.compile(r"([1-9][0-9]*)\.[1-4]")


def slug(track: str) -> str:
    """The file stem of a track's `Artist — Title`: accents folded, lower case, every run of
    other characters one `-`."""
    folded = unicodedata.normalize("NFKD", track).encode("ascii", "ignore").decode("ascii")
    return re.sub(r"[^a-z0-9]+", "-", folded.lower()).strip("-")


def _int(v) -> bool:
    return isinstance(v, int) and not isinstance(v, bool)


def _num(v) -> bool:
    return isinstance(v, (int, float)) and not isinstance(v, bool)


def _bar(v, bars: int) -> bool:
    return _int(v) and 1 <= v <= bars


def _downbeat_ms(text: str) -> int:
    m = DOWNBEAT_RE.fullmatch(text)
    return (int(m[1]) * 60 + int(m[2])) * 1000 + int(m[3])


def _per_bar(label: str, value, bars: int, alphabet: str) -> list[str]:
    if not isinstance(value, str):
        return [f"{label} is not a string"]
    out = []
    if len(value) != bars:
        out.append(f"{label} has {len(value)} characters, expected {bars}")
    if not re.fullmatch(f"[{alphabet}]*", value):
        out.append(f"{label} has characters outside [{alphabet}]")
    return out


def _step_list(label: str, value, bars: int, alphabet: str) -> list[str]:
    if not (isinstance(value, list) and value and all(isinstance(s, str) for s in value)):
        return [f"{label} is not a list of strings"]
    out = []
    total = sum(len(s) for s in value)
    if total != bars * STEPS_PER_BAR:
        out.append(f"{label} adds up to {total} characters, expected {bars * STEPS_PER_BAR}")
    if any(len(s) != STEP_CHUNK for s in value[:-1]) or not 0 < len(value[-1]) <= STEP_CHUNK:
        out.append(f"{label} must hold {STEP_CHUNK} characters per string, the last one fewer")
    if any(not re.fullmatch(f"[{alphabet}]*", s) for s in value):
        out.append(f"{label} has characters outside [{alphabet}]")
    return out


def _by_voice(label: str, value, voices: tuple[str, ...], check) -> list[str]:
    if not isinstance(value, dict):
        return [f"{label} is not a mapping"]
    out = []
    for key in value:
        if key not in voices:
            out.append(f"{label} has unexpected key {key!r}")
    for voice in voices:
        if voice not in value:
            out.append(f"{label}.{voice} is missing")
        else:
            out.extend(check(f"{label}.{voice}", value[voice]))
    return out


def _keys(label: str, value, required: tuple[str, ...], optional: tuple[str, ...] = ()) -> list[str]:
    if not isinstance(value, dict):
        return [f"{label} is not a mapping"]
    out = [f"{label} has unexpected key {k!r}" for k in value if k not in required + optional]
    out += [f"{label}.{k} is missing" for k in required if k not in value]
    return out


def _grid(grid) -> list[str]:
    out = _keys("grid", grid, ("bpm", "downbeat", "anchors", "offset_ms"))
    if out or not isinstance(grid, dict):
        return out
    if not (_num(grid["bpm"]) and grid["bpm"] > 0):
        out.append(f"grid.bpm {grid['bpm']!r} is not a positive number")
    down = grid["downbeat"]
    if not (isinstance(down, str) and DOWNBEAT_RE.fullmatch(down)):
        out.append(f"grid.downbeat {down!r} is not a time such as '0:00.061'")
        down = None
    if not _num(grid["offset_ms"]):
        out.append(f"grid.offset_ms {grid['offset_ms']!r} is not a number")
    anchors = grid["anchors"]
    if not (isinstance(anchors, list) and anchors):
        out.append("grid.anchors is not a list with at least one anchor")
        return out
    if not all(isinstance(a, list) and len(a) == 2 and _int(a[0]) and a[0] >= 0
               and _num(a[1]) and a[1] > 0 for a in anchors):
        out.append("grid.anchors holds entries that are not [ms, bpm]")
        return out
    if [a[0] for a in anchors] != sorted({a[0] for a in anchors}):
        out.append("grid.anchors are not sorted by time")
    first = anchors[0]  # a wrong first anchor is one problem: the time, else the tempo
    if down is not None and first[0] != _downbeat_ms(down):
        out.append("grid.anchors starts at a time other than grid.downbeat")
    elif _num(grid["bpm"]) and abs(first[1] - grid["bpm"]) > 1e-6:
        out.append("grid.anchors starts at a tempo other than grid.bpm")
    return out


def _beat(label: str, value, bars: int) -> list[str]:
    m = BEAT_RE.fullmatch(value) if isinstance(value, str) else None
    if not (m and int(m[1]) <= bars):
        return [f"{label} {value!r} is not a `bar.beat` inside 1..{bars}"]
    return []


def _voice(label: str, value, voice: str, bars: int) -> list[str]:
    own = voice.split(".")[-1]
    optional = ("entries", "exits") + (("balance",) if own in BALANCE_VOICES else ())
    out = _keys(label, value, ("bars",), optional)
    if not isinstance(value, dict):
        return out
    if "bars" in value:
        out += _per_bar(f"{label}.bars", value["bars"], bars, "0-9")
    if "balance" in value and own in BALANCE_VOICES:
        out += _per_bar(f"{label}.balance", value["balance"], bars, "LlcrR")
    for key in ("entries", "exits"):
        if key in value and not (isinstance(value[key], list)
                                 and all(_bar(b, bars) for b in value[key])):
            out.append(f"{label}.{key} is not a list of bars inside 1..{bars}")
    return out


def _hot_cues(data: dict, bars: int) -> list[str]:
    cues = data["hot_cues"]
    out = []
    if cues is None:
        if "hot_cues_note" not in data:
            out.append("hot_cues_note is missing, and hot_cues is null")
    elif not isinstance(cues, dict):
        out.append("hot_cues is not a mapping or null")
    else:
        for name, where in cues.items():
            if not (isinstance(name, str) and len(name) == 1 and name in CUE_NAMES):
                out.append(f"hot_cues has unexpected cue {name!r}")
            elif not (isinstance(where, str) and CUE_RE.fullmatch(where)
                      and int(where.split(".")[0]) <= bars):
                out.append(f"hot_cues.{name} {where!r} is not a `bar.beat` inside 1..{bars}")
        if "hot_cues_note" in data:
            out.append("hot_cues_note is present, and hot_cues is not null")
    if "hot_cues_note" in data and not isinstance(data["hot_cues_note"], str):
        out.append("hot_cues_note is not a string")
    return out


def _sections(sections, bars: int) -> list[str]:
    if not (isinstance(sections, list) and sections):
        return ["sections is not a non-empty list"]
    out = []
    spans = []
    for i, s in enumerate(sections):
        label = f"sections[{i}]"
        if not (isinstance(s, dict) and set(s) == {"bars", "kind"}):
            out.append(f"{label} is not a mapping with exactly `bars` and `kind`")
            continue
        if s["kind"] not in SECTION_KINDS:
            out.append(f"{label}.kind {s['kind']!r} is not one of {', '.join(SECTION_KINDS)}")
        b = s["bars"]
        if not (isinstance(b, list) and len(b) == 2 and all(_bar(x, bars) for x in b) and b[0] <= b[1]):
            out.append(f"{label}.bars {b!r} is not [first, last] inside 1..{bars}")
            continue
        spans.append(tuple(b))
    if len(spans) == len(sections):
        if spans[0][0] != 1:
            out.append("sections do not start at bar 1")
        for (_, prev_end), (start, _) in zip(spans, spans[1:]):
            if start <= prev_end:
                out.append("sections are not sorted or overlap")
            elif start > prev_end + 1:
                out.append(f"sections leave bars {prev_end + 1}..{start - 1} uncovered")
        if spans[-1][1] != bars:
            out.append(f"sections do not reach bar {bars}")
    return out


def _list_of(label: str, value, check) -> list[str]:
    if not isinstance(value, list):
        return [f"{label} is not a list"]
    return [p for i, item in enumerate(value) for p in check(f"{label}[{i}]", item)]


def _plain(value):
    """`value` without the validator's loader bookkeeping (`__line__` in every mapping)."""
    if isinstance(value, dict):
        return {k: _plain(v) for k, v in value.items() if k != "__line__"}
    if isinstance(value, list):
        return [_plain(v) for v in value]
    return value


def problems_map(data: object) -> list[str]:
    """Every way `data` (a parsed map file) breaks the schema; the pool match and the file
    name need the repo and are checked by the validator."""
    data = _plain(data)
    if not isinstance(data, dict):
        return ["the map is not a mapping"]
    out = [f"unexpected key {k!r}" for k in data if k not in KEYS]
    out += [f"{k} is missing" for k in REQUIRED if k not in data]
    if "map_version" in data and not (_int(data["map_version"]) and data["map_version"] == MAP_VERSION):
        out.append(f"map_version {data['map_version']!r} is not {MAP_VERSION}")
    track = data.get("track")
    if "track" in data and not (isinstance(track, str) and " — " in track):
        out.append(f"track {track!r} is not `Artist — Title` (em dash)")
    if "soundswitch" in data and not (isinstance(data["soundswitch"], str)
                                      and GUID_RE.fullmatch(data["soundswitch"])):
        out.append(f"soundswitch {data['soundswitch']!r} is not a GUID")
    if "audio" in data:
        audio = data["audio"]
        sub = _keys("audio", audio, ("sha256", "ms"))
        out += sub
        if not sub:
            if not (isinstance(audio["sha256"], str) and SHA_RE.fullmatch(audio["sha256"])):
                out.append("audio.sha256 is not 12 lower-case hex digits")
            if not (_int(audio["ms"]) and audio["ms"] > 0):
                out.append("audio.ms is not a positive integer")
    if "separator" in data and not isinstance(data["separator"], str):
        out.append("separator is not a string")
    if "grid_warning" in data and not isinstance(data["grid_warning"], str):
        out.append("grid_warning is not a string")
    bars = data.get("bars")
    if "bars" in data and not (_int(bars) and bars > 0):
        out.append(f"bars {bars!r} is not a positive integer")
    if not (_int(bars) and bars > 0):
        return out  # everything below is measured in bars
    if "grid" in data:
        out += _grid(data["grid"])
    if "hot_cues" in data:
        out += _hot_cues(data, bars)
    if "voices" in data:
        out += _by_voice("voices", data["voices"], VOICES,
                         lambda label, v: _voice(label, v, label, bars))
    if "steps" in data:
        out += _by_voice("steps", data["steps"], VOICES,
                         lambda label, v: _step_list(label, v, bars, "0-9"))
    if "onsets" in data:
        out += _by_voice("onsets", data["onsets"], ONSET_VOICES,
                         lambda label, v: _step_list(label, v, bars, r".1-9"))
    if "register" in data:
        out += _step_list("register", data["register"], bars, r".0-9")
    if "phrases" in data:
        out += _list_of("phrases", data["phrases"], lambda label, p: _phrase(label, p, bars))
    if "sections" in data:
        out += _sections(data["sections"], bars)
    if "drops" in data:
        out += _list_of("drops", data["drops"], lambda label, d: _drop(label, d, bars))
    if "silences" in data:
        out += _list_of("silences", data["silences"], lambda label, s: _silence(label, s, bars))
    return out


def _phrase(label: str, p, bars: int) -> list[str]:
    out = _keys(label, p, ("from", "to", "register", "level"))
    if out:
        return out
    out += _beat(f"{label}.from", p["from"], bars) + _beat(f"{label}.to", p["to"], bars)
    if p["register"] not in REGISTERS:
        out.append(f"{label}.register {p['register']!r} is not one of {', '.join(REGISTERS)}")
    if not (_int(p["level"]) and 0 <= p["level"] <= 9):
        out.append(f"{label}.level {p['level']!r} is not an integer from 0 to 9")
    return out


def _drop(label: str, d, bars: int) -> list[str]:
    out = _keys(label, d, ("bar", "db"))
    if out:
        return out
    if not _bar(d["bar"], bars):
        out.append(f"{label}.bar {d['bar']!r} is not a bar inside 1..{bars}")
    if not _num(d["db"]):
        out.append(f"{label}.db {d['db']!r} is not a number")
    return out


def _silence(label: str, s, bars: int) -> list[str]:
    if not (isinstance(s, list) and len(s) == 2 and all(_bar(x, bars) for x in s) and s[0] <= s[1]):
        return [f"{label} {s!r} is not [first, last] inside 1..{bars}"]
    return []


def _flow(value) -> str:
    text = yaml.safe_dump(value, default_flow_style=True, allow_unicode=True,
                          sort_keys=False, width=10**9)
    return text.removesuffix("\n...\n").removesuffix("\n")


def _chunked(value):
    """A step value (one string or a list of strings) as one string per 8 bars."""
    if isinstance(value, str):
        value = [value]
    if not (isinstance(value, list) and all(isinstance(s, str) for s in value)):
        return value
    text = "".join(value)
    return [text[i:i + STEP_CHUNK] for i in range(0, len(text), STEP_CHUNK)]


def dump_map(data: dict) -> str:
    """The map as YAML text: the generated-by comment, the keys in schema order, small
    mappings and lists in flow style. Step strings (`steps`, `onsets`, `register`) are given
    whole or in pieces and written one string per 8 bars."""
    data = dict(data)
    for key in ("steps", "onsets"):
        if isinstance(data.get(key), dict):
            data[key] = {v: _chunked(s) for v, s in data[key].items()}
    if "register" in data:
        data["register"] = _chunked(data["register"])
    lines = [HEADER]
    for key in KEYS:
        if key not in data:
            continue
        value = data[key]
        if key in ("voices", "steps", "onsets") and isinstance(value, dict):
            lines.append(f"{key}:")
            lines += [f"  {name}: {_flow(sub)}" for name, sub in value.items()]
        else:
            lines.append(f"{key}: {_flow(value)}")
    return "\n".join(lines) + "\n"


def load_map(path: Path) -> dict:
    return yaml.safe_load(Path(path).read_text(encoding="utf-8"))


# ------------------------------------------------------------ audio features ----
# Pure functions: arrays in, values out. numpy is imported inside them so that importing
# this module (the validator does) stays light.

BLEED_DB = 30.0       # a voice this far under the mix is separation bleed, not a voice
SILENT_DB = -120.0
DB_PER_DIGIT = 3.0
KICK_HZ = 150.0       # the drums stem below this is `kick`, the rest `perc`
LOUD_PERCENTILE = 95  # "loud level" of a voice: this percentile of its per-bar dB


def step_edges_ms(grid, audio_ms: int):
    """Step boundaries (1/16 notes) from bar 1 beat 1 to the end of the audio: `bars*16 + 1`
    values, every one clipped to `audio_ms` (so they never decrease)."""
    import numpy as np

    bars = grid.bar_at(audio_ms - 1)
    edges = [grid.ms(1 + i // STEPS_PER_BAR, 1 + (i % STEPS_PER_BAR) / 4)
             for i in range(bars * STEPS_PER_BAR + 1)]
    return np.minimum(np.array(edges, dtype=np.int64), audio_ms)


def map_sim_data(m: dict, end_ms: int | None = None) -> dict:
    """What the simulator draws of a map, in ms from the map's own anchors: `voices`
    ({voice: [[t, digit]]}, one point per 1/16 step), `sections` ({kind, start, end}, the end
    being the start of the bar after), `drops` ({bar, t}) and `cues` ({name, t}, hot cues with
    their stored offsets). Every time is clamped to [0, `end_ms`] (the page's end; no upper
    bound when None), so a cue before bar 1 or a last bar past the audio stays on the axis."""
    from soundswitch_format import Grid

    grid = Grid([(int(ms), float(bpm)) for ms, bpm in m["grid"]["anchors"]])
    edges = step_edges_ms(grid, m["audio"]["ms"])

    def clamp(t: int) -> int:
        return max(0, t if end_ms is None else min(t, end_ms))

    voices = {}
    for voice in VOICES:
        text = "".join(m["steps"][voice])
        voices[voice] = [[clamp(int(edges[i])), int(c) if c.isdigit() else 0]
                         for i, c in enumerate(text[:len(edges) - 1])]
    cues = []
    for name, where in sorted((m.get("hot_cues") or {}).items()):
        found = CUE_RE.fullmatch(where)
        bar, beat = where.split("+")[0].split("-")[0].split(".")
        off = int(found[1][:-2]) if found[1] else 0
        cues.append({"name": name, "t": clamp(grid.ms(int(bar), int(beat)) + off)})
    return {
        "voices": voices,
        "sections": [{"kind": s["kind"], "start": clamp(grid.ms(s["bars"][0])), "end": clamp(grid.ms(s["bars"][1] + 1))}
                     for s in m["sections"]],
        "drops": [{"bar": d["bar"], "t": clamp(grid.ms(d["bar"]))} for d in m["drops"]],
        "cues": cues,
    }


def _stereo(x):
    import numpy as np

    x = np.asarray(x, dtype=np.float32)
    return np.stack([x, x], axis=1) if x.ndim == 1 else x


def voices_from_stems(stems: dict, sr: int) -> dict:
    """The five `VOICES` as `(n, 2)` float32 from the stems `vocals, drums, bass, other`:
    the drums are split by an FFT mask at `KICK_HZ` into `kick` (below) and `perc`."""
    import numpy as np

    drums = _stereo(stems["drums"])
    n = len(drums)
    low = np.fft.rfftfreq(n, 1 / sr) < KICK_HZ
    kick = np.empty(drums.shape, dtype=np.float32)
    perc = np.empty(drums.shape, dtype=np.float32)
    for ch in range(drums.shape[1]):  # one channel at a time keeps the float64 spectra small
        spec = np.fft.rfft(drums[:, ch])
        kick[:, ch] = np.fft.irfft(spec * low, n=n)
        perc[:, ch] = np.fft.irfft(spec * ~low, n=n)
    return {"vocals": _stereo(stems["vocals"]), "kick": kick, "perc": perc,
            "bass": _stereo(stems["bass"]), "other": _stereo(stems["other"])}


def rms_db(x, sr: int, edges_ms):
    """RMS in dB per interval between consecutive `edges_ms`, the power averaged over the
    channels (so out-of-phase material does not cancel); `SILENT_DB` for silence or an empty
    interval."""
    import numpy as np

    x = np.asarray(x, dtype=np.float64)
    idx = np.clip(np.round(np.asarray(edges_ms) * sr / 1000).astype(np.int64), 0, len(x))
    out = np.full(len(idx) - 1, SILENT_DB)
    for i, (a, b) in enumerate(zip(idx[:-1], idx[1:])):
        if b > a:
            rms = float(np.sqrt(np.mean(x[a:b] ** 2)))
            if rms > 0:
                out[i] = max(SILENT_DB, 20 * np.log10(rms))
    return out


def loud_db(db) -> float:
    """The loud level of a voice: the `LOUD_PERCENTILE` of its per-bar dB, ignoring silent
    bars; `SILENT_DB` when all are silent."""
    import numpy as np

    db = np.asarray(db, dtype=np.float64)
    live = db[db > SILENT_DB]
    return float(np.percentile(live, LOUD_PERCENTILE)) if len(live) else SILENT_DB


def is_bleed(voice_loud_db: float, mix_loud_db: float) -> bool:
    """Whether a voice whose loud level is `voice_loud_db` is only separation bleed: more than
    `BLEED_DB` under the mix's loud level."""
    return voice_loud_db < mix_loud_db - BLEED_DB


def level_digits(db, voice_loud_db: float, mix_loud_db: float | None = None) -> str:
    """One digit per interval: 9 at `voice_loud_db`, one less per 3 dB below, 0 at 27 dB below
    or more. All 0 when the voice is bleed against `mix_loud_db` (no check when it is None:
    the caller decided)."""
    if mix_loud_db is not None and is_bleed(voice_loud_db, mix_loud_db):
        return "0" * len(db)
    return "".join(str(max(0, min(9, 9 - int((voice_loud_db - d) // DB_PER_DIGIT)))) for d in db)


def entries_exits(bar_digits: str) -> tuple[list[int], list[int]]:
    """1-based bars where a voice comes in and goes out. Entry: the first bar >= 5 after at
    least two quiet bars (<= 2), or at the start of the track. Exit: the last bar >= 5 before
    two quiet bars, or before the end. Bars of 3-4 neither arm an entry nor count as quiet."""
    entries, exits = [], []
    armed, quiet, last = True, 0, None
    for i, c in enumerate(bar_digits, 1):
        v = int(c)
        if v >= 5:
            if armed:
                entries.append(i)
                armed = False
            last, quiet = i, 0
        elif v <= 2:
            quiet += 1
            if quiet == 2:
                armed = True
                if last is not None:
                    exits.append(last)
                    last = None
        else:
            quiet = 0
    if last is not None:
        exits.append(last)
    return entries, exits


def balance_letters(x, sr: int, bar_edges_ms) -> str:
    """Per bar, the left-minus-right level: >= 6 dB `L`, >= 2 `l`, <= -6 `R`, <= -2 `r`, else
    `c` (silent bars are `c`)."""
    x = _stereo(x)
    left = rms_db(x[:, 0], sr, bar_edges_ms)
    right = rms_db(x[:, 1], sr, bar_edges_ms)
    letters = []
    for diff in left - right:
        letters.append("L" if diff >= 6 else "l" if diff >= 2 else "R" if diff <= -6
                       else "r" if diff <= -2 else "c")
    return "".join(letters)


ONSET_WIN_MS = 3.0     # energy window of the onset envelope
ONSET_HOP_MS = 1.0
ONSET_FLOOR_DB = 27.0  # an onset this far under the strongest one is not reported
ONSET_MIN_GAP_MS = 30.0
KICK_ATTACK_FLOOR_DB = 12.0  # a drum rise this far under the steepest nearby is no kick attack
KICK_NEAR_S = 1.0      # "nearby" for that: this far either side of the kick
KICK_NEXT_MS = 20.0    # a kick's attack is searched this long after the previous kick's
KICK_BODY_MS = 50.0    # a kick's strength is the drums' peak level within this long after its attack
KICK_ATTACK_BACK_MS = 100.0  # a kick's drum attack is looked for this far before its low-end onset
ONSET_ATTACK_MS = 10.0  # strength is the envelope rise over this long after the onset
PITCH_SR = 11025       # the pitch tracker decimates to about this rate
PITCH_MIN_HZ = 70.0
PITCH_MAX_HZ = 1000.0
YIN_THRESHOLD = 0.15
YIN_UNVOICED = 0.3     # a best normalised difference above this is no pitch (breath, sibilance)
PHRASE_GAP_STEPS = 4   # gaps shorter than this (a beat) do not split a phrase
VOICED_LEVEL = 3


def _mono(x):
    """`x` as one channel for measuring levels: the power averaged over the channels (so
    out-of-phase material does not cancel). Rectified, so never for pitch: see `_mix`."""
    import numpy as np

    x = np.asarray(x, dtype=np.float64)
    return x if x.ndim == 1 else np.sqrt(np.mean(x ** 2, axis=1))  # power over channels


def _mix(x):
    """`x` as one channel for pitch: the channels averaged, so the waveform keeps its period."""
    import numpy as np

    x = np.asarray(x, dtype=np.float64)
    return x if x.ndim == 1 else x.mean(axis=1)


def _onset_env(x, sr: int):
    """`(env, starts, hop)`: the short-window RMS of mono `x`, the sample where each window
    starts and the hop in samples; `env` is None when `x` is too short."""
    import numpy as np

    win = max(2, int(round(ONSET_WIN_MS * sr / 1000)))
    hop = max(1, int(round(ONSET_HOP_MS * sr / 1000)))
    if len(x) < win + hop:
        return None, None, hop
    csum = np.concatenate([[0.0], np.cumsum(x ** 2)])
    starts = np.arange(0, len(x) - win + 1, hop)
    return np.sqrt((csum[starts + win] - csum[starts]) / win), starts, hop


def _first_step_ms(edges) -> float:
    """The earliest onset time that still belongs to step 0: half a step before bar 1."""
    return float(edges[0] - (edges[1] - edges[0]) / 2) if len(edges) > 1 else float(edges[0])


def _strength_digits(best: dict, steps: int) -> str:
    """The onset string for `best` (step -> rise): 9 for the largest, one less per 3 dB below it."""
    import numpy as np

    digits = ["."] * steps
    for step, rise in best.items():
        below = 20 * np.log10(max(best.values()) / rise)
        digits[step] = str(max(1, min(9, 9 - int(below // DB_PER_DIGIT))))
    return "".join(digits)


def onset_digits(x, sr: int, edges_ms) -> tuple[str, list[float]]:
    """Per step `.` or `1`-`9`: onset strength, 9 for the track's strongest onset and one less
    per 3 dB below it. Onsets are peaks of the positive rise of a short-window energy envelope;
    each is quantised to the nearest step (the strongest wins a step); onsets more than half a
    step before bar 1 or after the last edge are left out. Also returns the onset times in ms.
    For `perc` (the drums above `KICK_HZ`, kick clicks included) this is the onset string as
    is; `kick` goes through `kick_onsets`."""
    import numpy as np

    edges = np.asarray(edges_ms, dtype=np.float64)
    steps = len(edges) - 1
    env, starts, hop = _onset_env(_mono(x), sr)
    if steps < 1 or env is None:
        return "." * max(steps, 0), []
    flux = np.maximum(0.0, np.diff(env, prepend=0.0))
    t_ms = starts * 1000 / sr
    inside = (t_ms >= _first_step_ms(edges)) & (t_ms <= edges[-1])  # audio outside the map has no say
    top = flux[inside].max() if inside.any() else 0.0
    if top <= 0:
        return "." * steps, []
    gap = max(1, int(round(ONSET_MIN_GAP_MS * sr / 1000 / hop)))
    reach = max(1, int(round(ONSET_ATTACK_MS * sr / 1000 / hop)))
    floor = top * 10 ** (-ONSET_FLOOR_DB / 20)
    times = []
    best = {}
    for i in np.flatnonzero(inside & (flux >= floor)):
        a, b = max(0, i - gap), min(len(flux), i + gap + 1)
        if i != a + int(np.argmax(flux[a:b])):
            continue
        t = t_ms[i]
        step = min(steps - 1, int(np.argmin(np.abs(edges - t))))
        times.append(float(t))
        rise = env[i:i + reach].max() - (env[i - 1] if i else 0.0)  # the whole attack, not one hop
        best[step] = max(best.get(step, 0.0), rise)
    return _strength_digits(best, steps), times


def kick_onsets(drums, kick, sr: int, edges_ms) -> tuple[str, list[float]]:
    """Like `onset_digits` for the kick, but timed at the drum attack. A real kick's energy
    below `KICK_HZ` builds after the attack, so the low band alone reads late. The onsets
    `onset_digits` finds on `kick` say that a kick happened; each is moved back to the steepest
    rise of the full `drums` stem's short-window energy within `KICK_ATTACK_BACK_MS` before it,
    but never earlier than `KICK_NEXT_MS` after the previous kept attack, so times strictly
    increase. An onset with no clear rise there (more than `KICK_ATTACK_FLOOR_DB` under the
    steepest drums rise within `KICK_NEAR_S` of it) is the low end ringing, not a hit, and is
    dropped. Strength is the drums' peak level within `KICK_BODY_MS` after the attack, 9 for
    the strongest and one less per 3 dB below it; it reads the whole drums stem, so a hat or
    snare on the kick adds to it. An attack more than half a step before bar 1 is left out.
    Returns the string and the times in ms."""
    import numpy as np

    edges = np.asarray(edges_ms, dtype=np.float64)
    steps = len(edges) - 1
    _, found = onset_digits(kick, sr, edges)
    env, starts, hop = _onset_env(_mono(drums), sr)
    if env is None or not found:
        return "." * steps, []
    flux = np.maximum(0.0, np.diff(env, prepend=0.0))
    ms_to_hops = sr / 1000 / hop
    back = max(1, int(round(KICK_ATTACK_BACK_MS * ms_to_hops)))
    after = max(1, int(round(KICK_NEXT_MS * ms_to_hops)))
    near = max(1, int(round(KICK_NEAR_S * 1000 * ms_to_hops)))
    reach = max(1, int(round(KICK_BODY_MS * ms_to_hops)))
    earliest = _first_step_ms(edges)
    times, best, prev = [], {}, None
    for t in found:
        i = min(len(flux) - 1, int(round(t * ms_to_hops)))
        a = max(0, i - back) if prev is None else max(i - back, prev + after)
        if a > i:
            continue
        j = a + int(np.argmax(flux[a:i + 1]))
        local = flux[max(0, i - near):i + near + 1].max()
        if flux[j] <= 0 or flux[j] < local * 10 ** (-KICK_ATTACK_FLOOR_DB / 20):
            continue
        prev = j
        attack = float(starts[j] * 1000 / sr)
        if attack < earliest:  # moved back to before bar 1: not in the map
            continue
        times.append(attack)
        step = min(steps - 1, int(np.argmin(np.abs(edges - attack))))
        best[step] = max(best.get(step, 0.0), env[j:j + reach].max())
    return _strength_digits(best, steps), times


def _yin_hz(frame, sr: float, tau_min: int, tau_max: int):
    """Pitch of `frame` (length >= 2 * tau_max) by YIN: difference function, cumulative mean
    normalisation, first dip under `YIN_THRESHOLD` (else the lowest); None if unvoiced."""
    import numpy as np

    w = len(frame) - tau_max
    a = frame[:w]
    n = 1 << (len(frame) + w).bit_length()
    corr = np.fft.irfft(np.fft.rfft(frame, n) * np.conj(np.fft.rfft(a, n)), n)[: tau_max + 1]
    csum = np.concatenate([[0.0], np.cumsum(frame ** 2)])
    idx = np.arange(tau_max + 1)
    d = csum[w] + (csum[idx + w] - csum[idx]) - 2 * corr
    d[0] = 0.0
    run = np.cumsum(d[1:])
    cm = np.ones(tau_max + 1)
    cm[1:] = d[1:] * np.arange(1, tau_max + 1) / np.maximum(run, 1e-12)
    cand = cm[tau_min:]
    below = np.flatnonzero(cand < YIN_THRESHOLD)
    if len(below):
        k = int(below[0])
        while k + 1 < len(cand) and cand[k + 1] < cand[k]:
            k += 1
    else:
        k = int(np.argmin(cand))
        if cand[k] > YIN_UNVOICED:
            return None
    tau = float(tau_min + k)
    if 0 < tau < tau_max:  # parabolic refinement
        p, q, r = cm[int(tau) - 1], cm[int(tau)], cm[int(tau) + 1]
        den = p - 2 * q + r
        if den > 1e-12:
            tau += 0.5 * (p - r) / den
    return sr / tau


def register_digits(x, sr: int, edges_ms, step_levels: str) -> str:
    """Per step `.` where `step_levels` is 0-2, else `0`-`9`: the median pitch of the step
    (YIN on the channels averaged, 70-1000 Hz, two frames per step) on a log scale within the
    track's own voiced range, its 5th percentile 0 and its 95th 9. A voiced step with no pitch
    is `.` too and is left out of the range."""
    import numpy as np

    edges = np.asarray(edges_ms, dtype=np.float64)
    x = _mix(x)
    dec = max(1, int(round(sr / PITCH_SR)))
    n = len(x) // dec * dec
    x = x[:n].reshape(-1, dec).mean(axis=1)
    rate = sr / dec
    tau_min = max(1, int(rate / PITCH_MAX_HZ))
    tau_max = int(np.ceil(rate / PITCH_MIN_HZ))
    flen = 3 * tau_max
    pitch: list[float | None] = []
    for i, level in enumerate(step_levels):
        if level in "012":
            pitch.append(None)
            continue
        found = []
        for frac in (0.25, 0.75):
            mid = (edges[i] + frac * (edges[i + 1] - edges[i])) * rate / 1000
            a = int(round(mid - flen / 2))
            if a < 0 or a + flen > len(x) or edges[i + 1] <= edges[i]:
                continue
            f = _yin_hz(x[a:a + flen], rate, tau_min, tau_max)
            if f is not None:
                found.append(np.log2(f))
        pitch.append(float(np.median(found)) if found else float("nan"))
    vals = np.array([p for p in pitch if p is not None and not np.isnan(p)])
    lo, hi = (np.percentile(vals, 5), np.percentile(vals, 95)) if len(vals) else (0.0, 0.0)
    out = []
    for p in pitch:
        if p is None or np.isnan(p):
            out.append(".")
        else:
            out.append(str(int(max(0, min(9, round(9 * (p - lo) / (hi - lo)))))) if hi > lo else "4")
    return "".join(out)


def _bar_beat(step: int) -> str:
    return f"{step // STEPS_PER_BAR + 1}.{step % STEPS_PER_BAR // 4 + 1}"


def phrases(step_levels: str, register: str) -> list[dict]:
    """Runs of voiced steps (level >= 3); a gap under `PHRASE_GAP_STEPS` does not split a run.
    Each is `{from, to, register, level}`: `bar.beat` of the first and last step, the register
    band (median of the pitched digits 0-3 low, 4-6 mid, 7-9 high; `mid` if none) and the highest
    step level in the run. Step k is bar k // 16 + 1, beat k % 16 // 4 + 1."""
    import numpy as np

    runs: list[list[int]] = []
    for i, c in enumerate(step_levels):
        if int(c) >= VOICED_LEVEL:
            if runs and i - runs[-1][1] - 1 < PHRASE_GAP_STEPS:
                runs[-1][1] = i
            else:
                runs.append([i, i])
    out = []
    for a, b in runs:
        digits = [int(c) for c in register[a:b + 1] if c != "."]
        med = float(np.median(digits)) if digits else 4.0
        out.append({"from": _bar_beat(a), "to": _bar_beat(b),
                    "register": "low" if med < 3.5 else "mid" if med < 6.5 else "high",
                    "level": max(int(c) for c in step_levels[a:b + 1])})
    return out


# ------------------------------------------------- sections, drops, grid, the map ----

FULL_DB = 6.0           # the low end (kick + bass) within this of its loud level: "full"
PRESENT_DB = 15.0       # ... and kick and bass each within this of their own loud level
WELL_BELOW_DB = 9.0     # the low end at least this far under its loud level: well below full
BREAK_MIN_BARS = 2
MIN_DROP_BARS = 2       # a drop shorter than this between two breaks is a stab in one break
BUILD_MIN_BARS = 2
BUILD_MAX_BARS = 16
BUILD_RISE_DB = 1.0     # a build bar is this much louder (perc + other) than the bar before
DROP_FLOOR_DB = 60.0    # kick + bass levels are floored this far under the loudest bar
SILENCE_DB = 40.0       # a bar this far under the mix's loud level is a silence
CUE_NEAR_MS = 30        # a hot cue farther than this from a beat gets its offset written


def _power_sum_db(*dbs):
    import numpy as np

    return 10 * np.log10(sum(10 ** (np.asarray(d, dtype=np.float64) / 10) for d in dbs))


def sections_and_drops(bar_db: dict) -> tuple[list[dict], list[dict]]:
    """Sections (`intro`, `groove`, `break`, `build`, `drop`, `outro`) and drops from the bar
    dB of the voices. The low end is the power sum of kick and bass. A bar is full when the low
    end is within `FULL_DB` of its loud level and kick and bass are each within `PRESENT_DB` of
    their own loud level (a loud kick alone is not full); it is well below full when the low end
    is at least `WELL_BELOW_DB` under its loud level (a filtered bass and kick count). A break
    starts with >= 2 well-below-full bars after full bars and runs until the next full bar: the
    bars after it that are neither full nor well below stay in it. A drop shorter than
    `MIN_DROP_BARS` between two breaks is a stab and joins them into one break; this applies
    between two breaks only, so a short full stretch right after the intro still starts a drop.
    The track's last full bar ends its groove/drop and the rest is the outro; before the first
    full bar is the intro (none when bar 1 is full: a groove). A break's trailing bars where
    perc + other rise bar over bar (2 to 16, never its first bar) are the build. A drop starts
    at the first full bar after the intro and after each break; its size is the kick + bass dB
    of that bar minus the mean of the (up to) two bars before, to one decimal; the levels are
    floored `DROP_FLOOR_DB` under the loudest bar, so a silent break is a bounded jump."""
    import numpy as np

    kick, bass = (np.asarray(bar_db[v], dtype=np.float64) for v in ("kick", "bass"))
    kb = _power_sum_db(kick, bass)
    n = len(kb)
    loud = loud_db(kb)
    live = loud > SILENT_DB + 10
    present = (kick >= loud_db(kick) - PRESENT_DB) & (bass >= loud_db(bass) - PRESENT_DB)
    full = [bool(live and d >= loud - FULL_DB and p) for d, p in zip(kb, present)]
    low = [bool(live and d <= loud - WELL_BELOW_DB) for d in kb]
    if not any(full):
        return [{"bars": [1, n], "kind": "intro"}], []
    first, last = full.index(True), n - 1 - full[::-1].index(True)
    breaks = []
    i = first
    while i <= last:
        if low[i]:
            j = i
            while j + 1 <= last and low[j + 1]:
                j += 1
            if j - i + 1 >= BREAK_MIN_BARS:
                while not full[j + 1]:  # the break lasts until the next full bar (`last` is one)
                    j += 1
                breaks.append((i, j))
            i = j + 1
        else:
            i += 1
    merged = []
    for a, b in breaks:  # a drop between two breaks shorter than MIN_DROP_BARS is part of the break
        if merged and a - merged[-1][1] - 1 < MIN_DROP_BARS:
            a = merged.pop()[0]
        merged.append((a, b))
    breaks = merged
    rise = _power_sum_db(bar_db["perc"], bar_db["other"])
    sections, drops = [], []

    def add(kind, a, b):  # 0-based inclusive
        sections.append({"bars": [a + 1, b + 1], "kind": kind})

    start, kind = 0, "groove"
    if first > 0:
        add("intro", 0, first - 1)
        start, kind = first, "drop"
    for a, b in breaks:
        if kind == "drop":
            drops.append(start)
        add(kind, start, a - 1)
        # walk back from the end over the rising bars
        k = b
        while k > a and rise[k] > rise[k - 1] + BUILD_RISE_DB and b - k + 1 <= BUILD_MAX_BARS:
            k -= 1
        build_from = k + 1
        if b - build_from + 1 >= BUILD_MIN_BARS and build_from > a:
            add("break", a, build_from - 1)
            add("build", build_from, b)
        else:
            add("break", a, b)
        start, kind = b + 1, "drop"
    if kind == "drop":
        drops.append(start)
    add(kind, start, last)
    if last < n - 1:
        add("outro", last + 1, n - 1)
    kb = np.maximum(kb, kb.max() - DROP_FLOOR_DB)  # a silent bar before is a jump of at most this
    out = []
    for bar in drops:
        before = kb[max(0, bar - 2):bar]
        out.append({"bar": bar + 1, "db": round(float(kb[bar] - np.mean(before)), 1)})
    return sections, out


def silences(mix_bar_db) -> list[list[int]]:
    """Runs of bars more than `SILENCE_DB` under the mix's loud level, as 1-based `[first, last]`."""
    import numpy as np

    db = np.asarray(mix_bar_db, dtype=np.float64)
    gone = db < loud_db(db) - SILENCE_DB
    out: list[list[int]] = []
    for i, g in enumerate(gone, 1):
        if g:
            if out and out[-1][1] == i - 1:
                out[-1][1] = i
            else:
                out.append([i, i])
    return out


def _nearest_beat(ms: float, grid) -> tuple[int, int, float]:
    """`(bar, beat, ms - beat time)` of the grid beat nearest to `ms`."""
    bar = max(1, grid.bar_at(int(ms)))
    cands = [(bar, beat) for beat in (1, 2, 3, 4)] + [(bar + 1, 1)]
    return min(((b, k, ms - grid.ms(b, k)) for b, k in cands), key=lambda c: abs(c[2]))


def grid_offset_ms(onset_ms, grid) -> float:
    """Median signed distance from each attack to the nearest beat; 0 when there are none.
    Onsets before the first anchor are left out."""
    import numpy as np

    first = grid.anchors[0][0]
    offs = [_nearest_beat(t, grid)[2] for t in onset_ms if t >= first]
    return float(np.median(offs)) if offs else 0.0


def cue_text(ms: int, grid) -> str:
    """`bar.beat` of the beat nearest to `ms`; more than `CUE_NEAR_MS` from it, the signed
    offset follows (`9.1+500ms`)."""
    bar, beat, off = _nearest_beat(ms, grid)
    text = f"{bar}.{beat}"
    return text + (f"{round(off):+d}ms" if abs(off) > CUE_NEAR_MS else "")


def is_stale(existing: dict, *, audio_sha: str, guid: str, anchors) -> bool:
    """True when the audio hash, the script's GUID or the tempo anchors differ from the map's."""
    stored = [(a[0], float(a[1])) for a in existing["grid"]["anchors"]]
    return (existing["audio"]["sha256"] != audio_sha or existing["soundswitch"] != guid
            or stored != [(int(ms), float(bpm)) for ms, bpm in anchors])


def _downbeat(ms: int) -> str:
    return f"{ms // 60000}:{ms // 1000 % 60:02d}.{ms % 1000:03d}"


def build_map(*, track: str, guid: str, audio_sha: str, audio_ms: int, anchors, stems: dict,
              sr: int, hot_cues, hot_cues_note, separator: str) -> dict:
    """The musical map (a dict that passes `problems_map` and dumps as is) of a track from its
    four stems `vocals, drums, bass, other` at `sr`. `anchors` are the script's `(ms, bpm)`;
    bar 1 is the first one, audio before it is not in the map. The mix, for the bleed rule and
    the silences, is the sum of the stems."""
    from soundswitch_format import Grid

    grid = Grid([(int(ms), float(bpm)) for ms, bpm in anchors])
    edges = step_edges_ms(grid, audio_ms)
    bar_edges = edges[::STEPS_PER_BAR]
    bars = len(bar_edges) - 1
    voices = voices_from_stems(stems, sr)
    mix = sum(_stereo(stems[k]) for k in ("vocals", "drums", "bass", "other"))
    mix_bar = rms_db(mix, sr, bar_edges)
    del mix
    step_db = {v: rms_db(voices[v], sr, edges) for v in VOICES}
    bar_db = {v: rms_db(voices[v], sr, bar_edges) for v in VOICES}
    # bleed is decided once per voice, on the bars, so the steps (and the register and phrases
    # read from them) never carry a voice the bars zero out
    bleed = {v: is_bleed(loud_db(bar_db[v]), loud_db(mix_bar)) for v in VOICES}

    def levels(db, v):
        return "0" * len(db) if bleed[v] else level_digits(db, loud_db(db))

    steps = {v: levels(step_db[v], v) for v in VOICES}
    bar_digits = {v: levels(bar_db[v], v) for v in VOICES}
    out_voices = {}
    for v in VOICES:
        entries, exits = entries_exits(bar_digits[v])
        entry = {"bars": bar_digits[v], "entries": entries, "exits": exits}
        if v in BALANCE_VOICES:
            entry["balance"] = balance_letters(voices[v], sr, bar_edges)
        out_voices[v] = entry
    onsets, onset_ms = {}, {}
    onsets["kick"], onset_ms["kick"] = kick_onsets(_stereo(stems["drums"]), voices["kick"], sr, edges)
    onsets["perc"], onset_ms["perc"] = onset_digits(voices["perc"], sr, edges)
    register = register_digits(voices["vocals"], sr, edges, steps["vocals"])
    offset = grid_offset_ms(onset_ms["kick"], grid)
    sections, drops = sections_and_drops(bar_db)
    first_ms, first_bpm = grid.anchors[0]
    data = {
        "map_version": MAP_VERSION,
        "track": track,
        "soundswitch": guid,
        "audio": {"sha256": audio_sha, "ms": int(audio_ms)},
        "grid": {"bpm": first_bpm, "downbeat": _downbeat(first_ms),
                 "anchors": [[ms, bpm] for ms, bpm in grid.anchors], "offset_ms": round(offset)},
    }
    step_ms = 60000 / first_bpm / 4
    if abs(offset) > step_ms / 4:  # a soft kick attack reads late too: name both causes
        data["grid_warning"] = (
            f"kick onsets sit {round(offset):+d} ms from the beat (more than a quarter of a step, "
            f"{step_ms / 4:.0f} ms): either the grid is off or the kick's attack is soft and "
            "onsets.kick reads late; check the grid against the audio")
    data.update({
        "separator": separator,
        "bars": bars,
        "hot_cues": hot_cues,
    })
    if hot_cues is None:
        data["hot_cues_note"] = hot_cues_note
    data.update({
        "voices": out_voices,
        "steps": {v: _chunked(steps[v]) for v in VOICES},
        "onsets": {v: _chunked(onsets[v]) for v in ONSET_VOICES},
        "register": _chunked(register),
        "phrases": phrases(steps["vocals"], register),
        "sections": sections,
        "drops": drops,
        "silences": silences(mix_bar),
    })
    return data


def fold_name(text: str) -> str:
    """A file or folder name made comparable: NFC, case-folded, NFC again."""
    return unicodedata.normalize("NFC", unicodedata.normalize("NFC", text).casefold())


def find_audio(root: Path, windows_path: str) -> Path:
    """The audio file under `root` that a rekordbox (Windows) path names.

    Base names are compared NFC-normalised and case-folded; several hits are narrowed to those
    whose parent folder has the same name. Anything but exactly one file is a `LookupError`.
    """
    parts = [p for p in re.split(r"[\\/]", windows_path) if p]
    if not parts:
        raise LookupError(f"no file name in the path {windows_path!r}")
    base = fold_name(parts[-1])
    folder = fold_name(parts[-2]) if len(parts) > 1 else None
    hits = sorted(p for p in Path(root).rglob("*") if p.is_file() and fold_name(p.name) == base)
    if len(hits) > 1:
        same = [p for p in hits if fold_name(p.parent.name) == folder]
        if same:
            hits = same
    if len(hits) == 1:
        return hits[0]
    if not hits:
        raise LookupError(f"no audio file named {parts[-1]!r} under {root}")
    raise LookupError(f"{len(hits)} audio files match {windows_path!r}: " + ", ".join(str(p) for p in hits))
