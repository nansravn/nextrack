"""The musical map of a track: the file format, its schema checks and its (de)serialisation.

A pure library: no I/O besides `load_map`, and no heavy imports at module level (the
validator, `check_repo.py`, imports this). Schema: the "Musical maps" section of `lightshows/README.md`.
"""
from __future__ import annotations

import re
import unicodedata
from pathlib import Path

import yaml

MAP_VERSION = 1
VOICES = ("vocals", "kick", "perc", "bass", "other")
STEPS_PER_BAR = 16
SECTION_KINDS = ("intro", "groove", "break", "build", "drop", "outro")
REGISTERS = ("low", "mid", "high")
CUE_NAMES = "ABCDEFGH"

HEADER = "# Generated by scripts/nextrack_map.py analyze. Do not edit by hand."
KEYS = (
    "map_version", "track", "soundswitch", "audio", "grid", "grid_warning", "separator", "bars",
    "hot_cues", "hot_cues_note", "voices", "steps", "onsets", "register", "phrases", "sections",
    "drops", "silences",
)
REQUIRED = tuple(k for k in KEYS if k not in ("grid_warning", "hot_cues_note"))
BALANCE_VOICES = ("perc", "other")
ONSET_VOICES = ("kick", "perc")
STEP_CHUNK = 8 * STEPS_PER_BAR  # step strings hold 8 bars

GUID_RE = re.compile(r"[0-9A-Fa-f]{8}-[0-9A-Fa-f]{4}-[0-9A-Fa-f]{4}-[0-9A-Fa-f]{4}-[0-9A-Fa-f]{12}")
DOWNBEAT_RE = re.compile(r"([0-9]+):([0-5][0-9])\.([0-9]{3})")
SHA_RE = re.compile(r"[0-9a-f]{12}")
CUE_RE = re.compile(r"[1-9][0-9]*\.[1-4]([+-][0-9]+ms)?")
BEAT_RE = re.compile(r"([1-9][0-9]*)\.[1-4]")


def slug(track: str) -> str:
    """The file stem of a track's `Artist — Title`: accents folded, lower case, every run of
    other characters one `-`."""
    folded = unicodedata.normalize("NFKD", track).encode("ascii", "ignore").decode("ascii")
    return re.sub(r"[^a-z0-9]+", "-", folded.lower()).strip("-")


def _int(v) -> bool:
    return isinstance(v, int) and not isinstance(v, bool)


def _num(v) -> bool:
    return isinstance(v, (int, float)) and not isinstance(v, bool)


def _bar(v, bars: int) -> bool:
    return _int(v) and 1 <= v <= bars


def _downbeat_ms(text: str) -> int:
    m = DOWNBEAT_RE.fullmatch(text)
    return (int(m[1]) * 60 + int(m[2])) * 1000 + int(m[3])


def _per_bar(label: str, value, bars: int, alphabet: str) -> list[str]:
    if not isinstance(value, str):
        return [f"{label} is not a string"]
    out = []
    if len(value) != bars:
        out.append(f"{label} has {len(value)} characters, expected {bars}")
    if not re.fullmatch(f"[{alphabet}]*", value):
        out.append(f"{label} has characters outside [{alphabet}]")
    return out


def _step_list(label: str, value, bars: int, alphabet: str) -> list[str]:
    if not (isinstance(value, list) and value and all(isinstance(s, str) for s in value)):
        return [f"{label} is not a list of strings"]
    out = []
    total = sum(len(s) for s in value)
    if total != bars * STEPS_PER_BAR:
        out.append(f"{label} adds up to {total} characters, expected {bars * STEPS_PER_BAR}")
    if any(len(s) != STEP_CHUNK for s in value[:-1]) or not 0 < len(value[-1]) <= STEP_CHUNK:
        out.append(f"{label} must hold {STEP_CHUNK} characters per string, the last one fewer")
    if any(not re.fullmatch(f"[{alphabet}]*", s) for s in value):
        out.append(f"{label} has characters outside [{alphabet}]")
    return out


def _by_voice(label: str, value, voices: tuple[str, ...], check) -> list[str]:
    if not isinstance(value, dict):
        return [f"{label} is not a mapping"]
    out = []
    for key in value:
        if key not in voices:
            out.append(f"{label} has unexpected key {key!r}")
    for voice in voices:
        if voice not in value:
            out.append(f"{label}.{voice} is missing")
        else:
            out.extend(check(f"{label}.{voice}", value[voice]))
    return out


def _keys(label: str, value, required: tuple[str, ...], optional: tuple[str, ...] = ()) -> list[str]:
    if not isinstance(value, dict):
        return [f"{label} is not a mapping"]
    out = [f"{label} has unexpected key {k!r}" for k in value if k not in required + optional]
    out += [f"{label}.{k} is missing" for k in required if k not in value]
    return out


def _grid(grid) -> list[str]:
    out = _keys("grid", grid, ("bpm", "downbeat", "anchors", "offset_ms"))
    if out or not isinstance(grid, dict):
        return out
    if not (_num(grid["bpm"]) and grid["bpm"] > 0):
        out.append(f"grid.bpm {grid['bpm']!r} is not a positive number")
    down = grid["downbeat"]
    if not (isinstance(down, str) and DOWNBEAT_RE.fullmatch(down)):
        out.append(f"grid.downbeat {down!r} is not a time such as '0:00.061'")
        down = None
    if not _num(grid["offset_ms"]):
        out.append(f"grid.offset_ms {grid['offset_ms']!r} is not a number")
    anchors = grid["anchors"]
    if not (isinstance(anchors, list) and anchors):
        out.append("grid.anchors is not a list with at least one anchor")
        return out
    if not all(isinstance(a, list) and len(a) == 2 and _int(a[0]) and a[0] >= 0
               and _num(a[1]) and a[1] > 0 for a in anchors):
        out.append("grid.anchors holds entries that are not [ms, bpm]")
        return out
    if [a[0] for a in anchors] != sorted({a[0] for a in anchors}):
        out.append("grid.anchors are not sorted by time")
    first = anchors[0]  # a wrong first anchor is one problem: the time, else the tempo
    if down is not None and first[0] != _downbeat_ms(down):
        out.append("grid.anchors starts at a time other than grid.downbeat")
    elif _num(grid["bpm"]) and abs(first[1] - grid["bpm"]) > 1e-6:
        out.append("grid.anchors starts at a tempo other than grid.bpm")
    return out


def _beat(label: str, value, bars: int) -> list[str]:
    m = BEAT_RE.fullmatch(value) if isinstance(value, str) else None
    if not (m and int(m[1]) <= bars):
        return [f"{label} {value!r} is not a `bar.beat` inside 1..{bars}"]
    return []


def _voice(label: str, value, voice: str, bars: int) -> list[str]:
    own = voice.split(".")[-1]
    optional = ("entries", "exits") + (("balance",) if own in BALANCE_VOICES else ())
    out = _keys(label, value, ("bars",), optional)
    if not isinstance(value, dict):
        return out
    if "bars" in value:
        out += _per_bar(f"{label}.bars", value["bars"], bars, "0-9")
    if "balance" in value and own in BALANCE_VOICES:
        out += _per_bar(f"{label}.balance", value["balance"], bars, "LlcrR")
    for key in ("entries", "exits"):
        if key in value and not (isinstance(value[key], list)
                                 and all(_bar(b, bars) for b in value[key])):
            out.append(f"{label}.{key} is not a list of bars inside 1..{bars}")
    return out


def _hot_cues(data: dict, bars: int) -> list[str]:
    cues = data["hot_cues"]
    out = []
    if cues is None:
        if "hot_cues_note" not in data:
            out.append("hot_cues_note is missing, and hot_cues is null")
    elif not isinstance(cues, dict):
        out.append("hot_cues is not a mapping or null")
    else:
        for name, where in cues.items():
            if not (isinstance(name, str) and len(name) == 1 and name in CUE_NAMES):
                out.append(f"hot_cues has unexpected cue {name!r}")
            elif not (isinstance(where, str) and CUE_RE.fullmatch(where)
                      and int(where.split(".")[0]) <= bars):
                out.append(f"hot_cues.{name} {where!r} is not a `bar.beat` inside 1..{bars}")
        if "hot_cues_note" in data:
            out.append("hot_cues_note is present, and hot_cues is not null")
    if "hot_cues_note" in data and not isinstance(data["hot_cues_note"], str):
        out.append("hot_cues_note is not a string")
    return out


def _sections(sections, bars: int) -> list[str]:
    if not (isinstance(sections, list) and sections):
        return ["sections is not a non-empty list"]
    out = []
    spans = []
    for i, s in enumerate(sections):
        label = f"sections[{i}]"
        if not (isinstance(s, dict) and set(s) == {"bars", "kind"}):
            out.append(f"{label} is not a mapping with exactly `bars` and `kind`")
            continue
        if s["kind"] not in SECTION_KINDS:
            out.append(f"{label}.kind {s['kind']!r} is not one of {', '.join(SECTION_KINDS)}")
        b = s["bars"]
        if not (isinstance(b, list) and len(b) == 2 and all(_bar(x, bars) for x in b) and b[0] <= b[1]):
            out.append(f"{label}.bars {b!r} is not [first, last] inside 1..{bars}")
            continue
        spans.append(tuple(b))
    if len(spans) == len(sections):
        if spans[0][0] != 1:
            out.append("sections do not start at bar 1")
        for (_, prev_end), (start, _) in zip(spans, spans[1:]):
            if start <= prev_end:
                out.append("sections are not sorted or overlap")
            elif start > prev_end + 1:
                out.append(f"sections leave bars {prev_end + 1}..{start - 1} uncovered")
        if spans[-1][1] != bars:
            out.append(f"sections do not reach bar {bars}")
    return out


def _list_of(label: str, value, check) -> list[str]:
    if not isinstance(value, list):
        return [f"{label} is not a list"]
    return [p for i, item in enumerate(value) for p in check(f"{label}[{i}]", item)]


def _plain(value):
    """`value` without the validator's loader bookkeeping (`__line__` in every mapping)."""
    if isinstance(value, dict):
        return {k: _plain(v) for k, v in value.items() if k != "__line__"}
    if isinstance(value, list):
        return [_plain(v) for v in value]
    return value


def problems_map(data: object) -> list[str]:
    """Every way `data` (a parsed map file) breaks the schema; the pool match and the file
    name need the repo and are checked by the validator."""
    data = _plain(data)
    if not isinstance(data, dict):
        return ["the map is not a mapping"]
    out = [f"unexpected key {k!r}" for k in data if k not in KEYS]
    out += [f"{k} is missing" for k in REQUIRED if k not in data]
    if "map_version" in data and not (_int(data["map_version"]) and data["map_version"] == MAP_VERSION):
        out.append(f"map_version {data['map_version']!r} is not {MAP_VERSION}")
    track = data.get("track")
    if "track" in data and not (isinstance(track, str) and " — " in track):
        out.append(f"track {track!r} is not `Artist — Title` (em dash)")
    if "soundswitch" in data and not (isinstance(data["soundswitch"], str)
                                      and GUID_RE.fullmatch(data["soundswitch"])):
        out.append(f"soundswitch {data['soundswitch']!r} is not a GUID")
    if "audio" in data:
        audio = data["audio"]
        sub = _keys("audio", audio, ("sha256", "ms"))
        out += sub
        if not sub:
            if not (isinstance(audio["sha256"], str) and SHA_RE.fullmatch(audio["sha256"])):
                out.append("audio.sha256 is not 12 lower-case hex digits")
            if not (_int(audio["ms"]) and audio["ms"] > 0):
                out.append("audio.ms is not a positive integer")
    if "separator" in data and not isinstance(data["separator"], str):
        out.append("separator is not a string")
    if "grid_warning" in data and not isinstance(data["grid_warning"], str):
        out.append("grid_warning is not a string")
    bars = data.get("bars")
    if "bars" in data and not (_int(bars) and bars > 0):
        out.append(f"bars {bars!r} is not a positive integer")
    if not (_int(bars) and bars > 0):
        return out  # everything below is measured in bars
    if "grid" in data:
        out += _grid(data["grid"])
    if "hot_cues" in data:
        out += _hot_cues(data, bars)
    if "voices" in data:
        out += _by_voice("voices", data["voices"], VOICES,
                         lambda label, v: _voice(label, v, label, bars))
    if "steps" in data:
        out += _by_voice("steps", data["steps"], VOICES,
                         lambda label, v: _step_list(label, v, bars, "0-9"))
    if "onsets" in data:
        out += _by_voice("onsets", data["onsets"], ONSET_VOICES,
                         lambda label, v: _step_list(label, v, bars, r".1-9"))
    if "register" in data:
        out += _step_list("register", data["register"], bars, r".0-9")
    if "phrases" in data:
        out += _list_of("phrases", data["phrases"], lambda label, p: _phrase(label, p, bars))
    if "sections" in data:
        out += _sections(data["sections"], bars)
    if "drops" in data:
        out += _list_of("drops", data["drops"], lambda label, d: _drop(label, d, bars))
    if "silences" in data:
        out += _list_of("silences", data["silences"], lambda label, s: _silence(label, s, bars))
    return out


def _phrase(label: str, p, bars: int) -> list[str]:
    out = _keys(label, p, ("from", "to", "register", "level"))
    if out:
        return out
    out += _beat(f"{label}.from", p["from"], bars) + _beat(f"{label}.to", p["to"], bars)
    if p["register"] not in REGISTERS:
        out.append(f"{label}.register {p['register']!r} is not one of {', '.join(REGISTERS)}")
    if not (_int(p["level"]) and 0 <= p["level"] <= 9):
        out.append(f"{label}.level {p['level']!r} is not an integer from 0 to 9")
    return out


def _drop(label: str, d, bars: int) -> list[str]:
    out = _keys(label, d, ("bar", "db"))
    if out:
        return out
    if not _bar(d["bar"], bars):
        out.append(f"{label}.bar {d['bar']!r} is not a bar inside 1..{bars}")
    if not _num(d["db"]):
        out.append(f"{label}.db {d['db']!r} is not a number")
    return out


def _silence(label: str, s, bars: int) -> list[str]:
    if not (isinstance(s, list) and len(s) == 2 and all(_bar(x, bars) for x in s) and s[0] <= s[1]):
        return [f"{label} {s!r} is not [first, last] inside 1..{bars}"]
    return []


def _flow(value) -> str:
    text = yaml.safe_dump(value, default_flow_style=True, allow_unicode=True,
                          sort_keys=False, width=10**9)
    return text.removesuffix("\n...\n").removesuffix("\n")


def _chunked(value):
    """A step value (one string or a list of strings) as one string per 8 bars."""
    if isinstance(value, str):
        value = [value]
    if not (isinstance(value, list) and all(isinstance(s, str) for s in value)):
        return value
    text = "".join(value)
    return [text[i:i + STEP_CHUNK] for i in range(0, len(text), STEP_CHUNK)]


def dump_map(data: dict) -> str:
    """The map as YAML text: the generated-by comment, the keys in schema order, small
    mappings and lists in flow style. Step strings (`steps`, `onsets`, `register`) are given
    whole or in pieces and written one string per 8 bars."""
    data = dict(data)
    for key in ("steps", "onsets"):
        if isinstance(data.get(key), dict):
            data[key] = {v: _chunked(s) for v, s in data[key].items()}
    if "register" in data:
        data["register"] = _chunked(data["register"])
    lines = [HEADER]
    for key in KEYS:
        if key not in data:
            continue
        value = data[key]
        if key in ("voices", "steps", "onsets") and isinstance(value, dict):
            lines.append(f"{key}:")
            lines += [f"  {name}: {_flow(sub)}" for name, sub in value.items()]
        else:
            lines.append(f"{key}: {_flow(value)}")
    return "\n".join(lines) + "\n"


def load_map(path: Path) -> dict:
    return yaml.safe_load(Path(path).read_text(encoding="utf-8"))
