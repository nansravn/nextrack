def test_vocab_lists_anchors_gestures_rules_and_the_shows_looks(mini_repo, capsys):
    import show_gestures
    import show_rules

    put_show(mini_repo)
    code, out = run(mini_repo, capsys, "vocab")
    assert code == 0
    assert "anchor := term" in out and "intro" in out and "outro" in out
    for word in ("sweep", "rows-up", "pulse", "1/16", "bar"):
        assert word in out
    for name in show_gestures.GESTURES:
        assert f"gesture {name}" in out
    for name in show_rules.RULES:
        assert f"rule {name}" in out
    assert "respiracao" not in out
    code, out = run(mini_repo, capsys, "vocab", "teste")
    assert code == 0
    assert "azul" in out and "#0A2CFF" in out
    assert "look respiracao" in out and "look pulso" in out


