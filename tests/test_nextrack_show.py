import shutil

import pytest
import yaml
from showdata import FILE_1, FILE_2, put_show

import nextrack_show

SHOW = "lightshows/shows/teste"
T1 = f"lightshows/tracks/{FILE_1}"
T2 = f"lightshows/tracks/{FILE_2}"


def run(repo, capsys, *args):
    code = nextrack_show.main([*args, "--repo", str(repo.root)])
    return code, capsys.readouterr().out


def _remove_generated(repo):
    for rel in (T1, T2):
        repo.path(rel).unlink()


def _edit_yaml(repo, rel, change):
    data = yaml.safe_load(repo.read(rel))
    change(data)
    repo.write(rel, yaml.safe_dump(data, allow_unicode=True, sort_keys=False))


def _budget_zero(data):
    data["rules"] = {"budget": {"pulso": {"max": 0}}}


def test_build_writes_and_is_idempotent(mini_repo, capsys):
    put_show(mini_repo)
    _remove_generated(mini_repo)
    code, out = run(mini_repo, capsys, "build", "teste")
    assert code == 0
    assert out.splitlines() == [f"wrote {T1}", f"wrote {T2}"]
    code, out = run(mini_repo, capsys, "build", "teste")
    assert code == 0
    assert out.splitlines() == [f"unchanged {T1}", f"unchanged {T2}"]
    assert mini_repo.findings() == []


def test_build_accepts_a_folder_path(mini_repo, capsys):
    put_show(mini_repo)
    code, out = run(mini_repo, capsys, "build", str(mini_repo.path(SHOW)))
    assert code == 0 and "unchanged" in out


def test_build_check_reports_drift(mini_repo, capsys):
    put_show(mini_repo)
    edited = mini_repo.read(T1) + "# edited\n"
    mini_repo.write(T1, edited)
    code, out = run(mini_repo, capsys, "build", "teste", "--check")
    assert code == 1
    assert f"would change {T1}" in out and T2 not in out
    assert mini_repo.read(T1) == edited


def test_build_check_is_clean_when_nothing_differs(mini_repo, capsys):
    put_show(mini_repo)
    code, out = run(mini_repo, capsys, "build", "teste", "--check")
    assert (code, out) == (0, "")


def test_build_refuses_hand_written_files_without_adopt(mini_repo, capsys):
    put_show(mini_repo)
    hand = "\n".join(mini_repo.read(T1).splitlines()[2:]) + "\n"  # no header
    mini_repo.write(T1, hand)
    mini_repo.path(T2).unlink()
    code, out = run(mini_repo, capsys, "build", "teste")
    assert code == 1
    assert f"refused {T1}: not generated by a show; use --adopt to take it over" in out
    assert mini_repo.read(T1) == hand
    assert not mini_repo.path(T2).exists()  # nothing written, not even the clean target
    code, out = run(mini_repo, capsys, "build", "teste", "--adopt")
    assert code == 0
    assert f"wrote {T1}" in out and f"wrote {T2}" in out
    assert mini_repo.findings() == []


def test_build_refuses_another_shows_file(mini_repo, capsys):
    put_show(mini_repo)
    text = mini_repo.read(T1).replace("from lightshows/shows/teste/.", "from lightshows/shows/outro/.", 1)
    mini_repo.write(T1, text)
    code, out = run(mini_repo, capsys, "build", "teste", "--adopt")
    assert code == 1
    assert f"refused {T1}: generated by lightshows/shows/outro" in out
    assert mini_repo.read(T1) == text


def test_build_writes_nothing_on_a_source_finding(mini_repo, capsys):
    put_show(mini_repo)
    _remove_generated(mini_repo)
    mini_repo.edit(f"{SHOW}/{FILE_1}", "at: drop.1", "at: drop.9")
    code, out = run(mini_repo, capsys, "build", "teste")
    assert code == 1
    assert f"{SHOW}/{FILE_1}:" in out and "show-source:" in out and "1 finding" in out
    assert "wrote" not in out
    assert not mini_repo.path(T1).exists() and not mini_repo.path(T2).exists()


def test_build_writes_despite_rule_findings(mini_repo, capsys):
    put_show(mini_repo)
    _remove_generated(mini_repo)
    _edit_yaml(mini_repo, f"{SHOW}/show.yml", _budget_zero)
    code, out = run(mini_repo, capsys, "build", "teste")
    assert code == 1
    assert f"wrote {T1}" in out and f"wrote {T2}" in out
    assert "show-rules: budget:" in out and "finding" in out.splitlines()[-1]
    assert mini_repo.path(T1).exists() and mini_repo.path(T2).exists()


def test_build_out_writes_a_variant_elsewhere(mini_repo, tmp_path, capsys):
    put_show(mini_repo)
    variant = tmp_path / "variant"
    shutil.copytree(mini_repo.path(SHOW), variant)
    before = (mini_repo.read(T1), mini_repo.read(T2))
    out_dir = tmp_path / "scratch" / "out"
    code, out = run(mini_repo, capsys, "build", str(variant), "--out", str(out_dir))
    assert code == 0
    assert out.splitlines() == [f"wrote {out_dir / FILE_1}", f"wrote {out_dir / FILE_2}"]
    assert (out_dir / FILE_1).read_text(encoding="utf-8").startswith("# Generated by scripts/nextrack_show.py")
    assert (mini_repo.read(T1), mini_repo.read(T2)) == before
    assert not list(out_dir.glob("*.tmp"))


