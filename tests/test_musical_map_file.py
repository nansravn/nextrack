from mapdata import good_map

import musical_map as mm


def test_slug_matches_the_choreography_naming():
    assert mm.slug("Marshmello x Bastille — Happier") == "marshmello-x-bastille-happier"
    assert mm.slug("&ME, Black Coffee — The Rapture Pt.III") == "me-black-coffee-the-rapture-pt-iii"
    assert mm.slug("Barbatuques — Baianá (Pablo Fierro Edit)") == "barbatuques-baiana-pablo-fierro-edit"


def test_a_good_map_has_no_problems(tmp_path):
    data = good_map()
    assert mm.problems_map(data) == []
    path = tmp_path / "m.yml"
    path.write_text(mm.dump_map(data), encoding="utf-8")
    assert mm.load_map(path) == data


def test_good_maps_of_other_sizes_have_no_problems():
    for bars in (1, 2, 8, 9, 10):
        assert mm.problems_map(good_map(bars)) == [], bars


def test_dump_starts_with_the_generated_comment_and_splits_steps_per_8_bars(tmp_path):
    text = mm.dump_map(good_map(10))
    assert text.splitlines()[0] == "# Generated by scripts/nextrack_map.py analyze. Do not edit by hand."
    keys = [line.split(":")[0] for line in text.splitlines() if line and line[0].isalpha()]
    assert keys[:4] == ["map_version", "track", "soundswitch", "audio"]
    path = tmp_path / "m.yml"
    path.write_text(text, encoding="utf-8")
    assert [len(s) for s in mm.load_map(path)["steps"]["vocals"]] == [128, 32]


def _set(path, value):
    def mutate(d):
        node = d
        for key in path[:-1]:
            node = node[key]
        node[path[-1]] = value
    return mutate


def _delete(path):
    def mutate(d):
        node = d
        for key in path[:-1]:
            node = node[key]
        del node[path[-1]]
    return mutate


MUTATIONS = [
    ("map_version", _set(["map_version"], 2)),
    ("audio", _delete(["audio"])),
    ("surprise", _set(["surprise"], 1)),
    ("voices.vocals.bars", _set(["voices", "vocals", "bars"], "555")),
    ("voices.kick.bars", _set(["voices", "kick", "bars"], "55a5")),
    ("steps.vocals", _set(["steps", "vocals"], ["5" * 63])),
    ("onsets.kick", _set(["onsets", "kick"], ["0" * 64])),
    ("register", _set(["register"], ["x" * 64])),
    ("balance", _set(["voices", "bass", "balance"], "cccc")),
    ("sections[0].kind", _set(["sections", 0, "kind"], "chorus")),
    ("sections are not sorted or overlap",
     _set(["sections"], [{"bars": [1, 3], "kind": "groove"}, {"bars": [3, 4], "kind": "drop"}])),
    ("sections leave bars 2..2 uncovered",
     _set(["sections"], [{"bars": [1, 1], "kind": "groove"}, {"bars": [3, 4], "kind": "drop"}])),
    ("sections do not reach bar 4", _set(["sections"], [{"bars": [1, 3], "kind": "groove"}])),
    ("drops[0].bar", _set(["drops", 0, "bar"], 5)),
    ("phrases[0].to", _set(["phrases", 0, "to"], "5.1")),
    ("hot_cues", _set(["hot_cues"], {"I": "1.1"})),
    ("hot_cues", _set(["hot_cues"], {1: "1.1"})),
    ("hot_cues", _set(["hot_cues"], {None: "1.1"})),
    ("hot_cues_note", _set(["hot_cues"], None)),
    ("hot_cues_note", _set(["hot_cues_note"], "none set")),
    ("grid.anchors", _set(["grid", "anchors"], [])),
]


@pytest.mark.parametrize("key,mutate", MUTATIONS)
def test_each_schema_violation_is_reported(key, mutate):
    data = copy.deepcopy(good_map(4))
    mutate(data)
    problems = mm.problems_map(data)
    assert len(problems) == 1, problems
    assert key in problems[0]


def test_hot_cues_may_be_null_with_a_note():
    data = good_map(4, hot_cues=None, hot_cues_note="not set in rekordbox")
    assert mm.problems_map(data) == []


def test_a_map_that_is_not_a_mapping_is_one_problem():
    assert len(mm.problems_map([1, 2])) == 1


def test_dump_keeps_unicode_readable():
    assert "Dançarina" in mm.dump_map(good_map())
    assert yaml.safe_load(mm.dump_map(good_map()))["track"] == "Pedro Sampaio — Dançarina"


def test_dump_chunks_whole_step_strings_itself(tmp_path):
    data = good_map(10)
    whole = {v: "".join(s) for v, s in data["steps"].items()}
    data["steps"] = whole
    data["onsets"] = {v: "".join(s) for v, s in data["onsets"].items()}
    data["register"] = "".join(data["register"])
    path = tmp_path / "m.yml"
    path.write_text(mm.dump_map(data), encoding="utf-8")
    loaded = mm.load_map(path)
    assert [len(s) for s in loaded["steps"]["vocals"]] == [128, 32]
    assert mm.problems_map(loaded) == []


def _touch(root, *parts):
    p = root.joinpath(*parts)
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_bytes(b"")
    return p


@pytest.mark.parametrize("path, name", [
    (r"C:\Music\afro-house\X.flac", "X.flac"), ("C:/Music/afro-house/X.flac", "X.flac"),
    ("/music/X.flac", "X.flac"), ("X.flac", "X.flac"), ("C:\\Music\\", "Music"),
    ("", ""), ("\\\\", ""),
])
def test_base_name_of_windows_and_posix_paths(path, name):
    assert mm.base_name(path) == name


def test_find_audio_one_match(tmp_path):
    want = _touch(tmp_path, "afro-house", "X.flac")
    assert mm.find_audio(tmp_path, "C:/Music/afro-house/X.flac") == want


def test_find_audio_prefers_the_same_folder(tmp_path):
    _touch(tmp_path, "other", "X.flac")
    want = _touch(tmp_path, "afro-house", "X.flac")
    assert mm.find_audio(tmp_path, "C:\\Music\\afro-house\\X.flac") == want


def test_find_audio_refuses_ambiguous(tmp_path):
    a = _touch(tmp_path, "one", "X.flac")
    b = _touch(tmp_path, "two", "X.flac")
    with pytest.raises(LookupError) as e:
        mm.find_audio(tmp_path, "C:/Music/afro-house/X.flac")
    assert str(a) in str(e.value) and str(b) in str(e.value)


def test_find_audio_none(tmp_path):
    with pytest.raises(LookupError):
        mm.find_audio(tmp_path, "C:/Music/afro-house/X.flac")


def test_find_audio_nfc_nfd_and_case(tmp_path):
    import unicodedata

    name = unicodedata.normalize("NFD", "Baianá.flac")
    want = _touch(tmp_path, "g", name)
    assert mm.find_audio(tmp_path, "C:/M/g/" + unicodedata.normalize("NFC", "BAIANÁ.FLAC")) == want


def test_find_audio_same_folder_name_twice_is_ambiguous(tmp_path):
    _touch(tmp_path, "a", "g", "X.flac")
    _touch(tmp_path, "b", "g", "X.flac")
    with pytest.raises(LookupError):
        mm.find_audio(tmp_path, "C:/M/g/X.flac")


def test_find_audio_nfd_folder_still_matches(tmp_path):
    import unicodedata

    _touch(tmp_path, "z", "X.flac")
    want = _touch(tmp_path, unicodedata.normalize("NFD", "Pé"), "X.flac")
    assert mm.find_audio(tmp_path, "C:/M/Pé/X.flac") == want


