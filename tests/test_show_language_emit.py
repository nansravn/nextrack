"""The emitter: exact layout, round trip, determinism and the ownership header."""
import yaml

import lightshow
from show_language import HEADER_RE, compile_show, emit_choreography, owner_of
from showdata import two_track_show

FOLDER = "lightshows/shows/teste"


def _choreo(story="Uma história curta.", intent="Ponte: a mesma luz."):
    return {
        "track": "PAWSA — Too Cool To Be Careless",
        "soundswitch": "A70F52BF-5680-4CE3-B9FA-984EEEF608AE",
        "grid": {"bpm": 128, "downbeat": "0:00.297"},
        "story": story,
        "base": "autoscript",
        "sections": [{
            "bars": [1, 15], "name": "ponte", "intent": intent,
            "movers": {"colour": "#6A1CFF", "every": "1/2", "move": "pingpong",
                       "positions": ["Dance Floor Centre", "Crossed Over", "Up"]},
            "matrix": {"mirror": True, "colour": "#0A2CFF", "rate": "1/2", "draw": "rows-up"},
            "hue": {"colour": "#B0001E", "state": "pulse"},
        }],
    }


def test_emit_matches_the_layout():
    story = ("TOO COOL é a virada da noite, do afro para o tech. Entra inteiro por baixo do Move; "
             "quando o grave volta do filtro, o vermelho já bate no centro.")
    choreo = _choreo(story=story)
    choreo["budget"] = "Gasta pouco."
    choreo["sections"].append({"bars": [16, 20], "name": "filtro", "movers": "off", "matrix": "auto",
                               "white": {"accent": ["16.1", "18.3"]}, "uv": "on", "hue": "dark",
                               "strobe": {"hit": ["20.1"]}})
    expected = """\
# Generated by scripts/nextrack_show.py build from lightshows/shows/teste/.
# Do not edit by hand: change the show and run the build again.
track: "PAWSA — Too Cool To Be Careless"
soundswitch: A70F52BF-5680-4CE3-B9FA-984EEEF608AE
grid: {bpm: 128, downbeat: "0:00.297"}
story: >-
  TOO COOL é a virada da noite, do afro para o tech. Entra inteiro por baixo do Move; quando o
  grave volta do filtro, o vermelho já bate no centro.
budget: >-
  Gasta pouco.
base: autoscript
sections:
  - bars: [1, 15]
    name: ponte
    intent: "Ponte: a mesma luz."
    movers: {move: pingpong, every: "1/2", colour: "#6A1CFF", positions: [Dance Floor Centre, Crossed Over, Up]}
    matrix: {draw: rows-up, rate: "1/2", colour: "#0A2CFF", mirror: true}
    hue: {state: pulse, colour: "#B0001E"}

  - bars: [16, 20]
    name: filtro
    movers: "off"
    matrix: auto
    white: {accent: ["16.1", "18.3"]}
    uv: "on"
    strobe: {hit: ["20.1"]}
    hue: dark
"""
    assert emit_choreography(choreo, FOLDER) == expected
    assert yaml.safe_load(expected) is not None


def test_emit_empty_sections():
    choreo = _choreo()
    choreo["sections"] = []
    text = emit_choreography(choreo, FOLDER)
    assert text.endswith("base: autoscript\nsections: []\n")
    assert yaml.safe_load(text)["sections"] == []


def test_emit_round_trips_tricky_prose():
    for text in ['Ponte: a mesma luz', 'o "coração" e o # da sala', '“aspas”', '- começa com traço',
                 'dois  espaços', 'acentuação ç ã é', 'x' * 300, 'linha\nnova\ttab', 'barra \\ e "aspa"',
                 ' espaço antes', 'espaço depois ', 'null']:
        choreo = _choreo(story=text, intent=text)
        parsed = yaml.safe_load(emit_choreography(choreo, FOLDER))
        assert parsed["story"] == text and parsed["sections"][0]["intent"] == text


def test_emit_folds_the_story_at_96_columns():
    text = emit_choreography(_choreo(story="palavra " * 40), FOLDER)
    body = [ln for ln in text.split("\n") if ln.startswith("  ") and not ln.startswith("  -")
            and not ln.startswith("    ")]
    assert body and all(len(ln) <= 96 for ln in body)


def test_emit_round_trips_the_compiled_show():
    show, _ = compile_show(*two_track_show())
    for t in show.tracks:
        assert yaml.safe_load(emit_choreography(t.choreography, show.folder)) == t.choreography


def test_emit_is_deterministic_and_valid():
    show, _ = compile_show(*two_track_show())
    for t in show.tracks:
        first = emit_choreography(t.choreography, show.folder)
        assert emit_choreography(t.choreography, show.folder) == first
        assert lightshow.problems_choreography(yaml.safe_load(first)) == []


def test_unknown_layer_keys_go_last_sorted():
    choreo = _choreo()
    choreo["sections"][0]["hue"] = {"zeta": 1, "colour": "#B0001E", "alpha": 0.7, "state": "pulse"}
    assert "hue: {state: pulse, colour: \"#B0001E\", alpha: 0.7, zeta: 1}" in emit_choreography(choreo, FOLDER)


def test_owner_of():
    assert owner_of(emit_choreography(_choreo(), FOLDER)) == FOLDER
    assert owner_of("# Coreografia de luz — rascunho v1\ntrack: x\n") is None
    assert owner_of("") is None
    assert HEADER_RE.fullmatch("# Generated by scripts/nextrack_show.py build from a/b/.")
